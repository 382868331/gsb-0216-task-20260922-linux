"""Fixed-input demonstration for the plackett_luce package.

Run:

    python demo.py

It (1) fits a small deterministic set of top-k observations with differing
participant sets (including one k=0 observation), prints the abilities and
ranking probabilities, and (2) actually triggers and prints one rejected
illegal input (a repeated object inside one ranking).  Everything is computed
live; no results are pre-recorded.
"""

from __future__ import annotations

import math

from plackett_luce import (
    Ranking,
    fit_plackett_luce,
    log_ranking_likelihood,
    ranking_probability,
    winner_probabilities,
)

NAMES = ("A", "B", "C", "D", "E")


def build_observations() -> list[Ranking]:
    """Deterministic fixed sample (5 objects, top-k, varying participant sets).

    Multiplicities are explicit, so the data is generated by code in-repo
    with no randomness, files, network or clock dependency.
    """
    obs: list[Ranking] = []
    # Strong A: A wins or leads frequently, even in restricted fields.
    obs += [Ranking((0, 2), (0, 1, 2, 3, 4))] * 4
    obs += [Ranking((0,), (0, 2, 4))] * 3
    obs += [Ranking((0, 1), (0, 1))] * 2
    # Mid field B/C.
    obs += [Ranking((1, 0, 2), (0, 1, 2))] * 2
    obs += [Ranking((2, 1), (1, 2, 3))] * 2
    obs += [Ranking((1,), (1, 3, 4))]
    # Weak D/E with occasional restricted-set wins.
    obs += [Ranking((3, 4), (3, 4))] * 2
    obs += [Ranking((4,), (3, 4))]
    # A top-3 observation that leaves two participants unranked (they stay
    # in every denominator) ...
    obs += [Ranking((0, 2, 1), (0, 1, 2, 3, 4))]
    # ... and a k=0 observation (no ordering recorded; contributes log 1).
    obs += [Ranking((), (0, 1, 2, 3, 4))]
    return obs


def main() -> None:
    observations = build_observations()
    lam = 0.5
    print("=" * 68)
    print("Plackett-Luce fit on partial top-k rankings")
    print("=" * 68)
    print(f"objects: {len(NAMES)}  observations: {len(observations)}  "
          f"lambda: {lam}")

    result = fit_plackett_luce(observations, n_objects=len(NAMES), lam=lam)
    print(f"status       : {result.status}")
    print(f"converged    : {result.converged}")
    print(f"iterations   : {result.iterations}")
    print(f"|proj grad|∞ : {result.grad_norm:.3e}")
    print(f"log-lik (sum): {result.log_likelihood:.6f}")
    print(f"penalty      : {result.penalty:.6f}")
    print(f"objective    : {result.objective:.6f}")

    print("\nFitted abilities (sum constrained to 0):")
    order = sorted(range(len(NAMES)), key=lambda i: -result.theta[i])
    for rank, i in enumerate(order, start=1):
        print(f"  {rank}. {NAMES[i]:>1}  theta = {result.theta[i]:+.4f}")
    print(f"  sum(theta) = {sum(result.theta):+.2e}")

    print("\nWin probabilities in a full-field selection:")
    p = winner_probabilities(result.theta)
    for i in order:
        print(f"  P(winner = {NAMES[i]}) = {p[i]:.4f}")
    print(f"  sum = {sum(p):.10f}")

    print("\nProbabilities of example partial rankings:")
    examples = [
        ((0, 2, 1), None, "top-3 A>C>B, full field (D,E unranked)"),
        ((0,), (0, 2, 4), "A wins the restricted field {A,C,E}"),
        ((3, 4), (3, 4), "complete order D>E over {D,E}"),
        ((), None, "k=0 observation (no ordering) -> log p = 0"),
    ]
    for ranked, participants, label in examples:
        lp = log_ranking_likelihood(ranked, result.theta, participants)
        pr = ranking_probability(ranked, result.theta, participants)
        seq = ">".join(NAMES[i] for i in ranked) if ranked else "(empty)"
        print(f"  {label}")
        print(f"      {seq}: log p = {lp:+.6f}, p = {pr:.6f}")

    print("\nFirst three per-observation contributions:")
    for c in result.contributions[:3]:
        seq = ">".join(NAMES[i] for i in c.ranked) or "(k=0)"
        field = "{" + ",".join(NAMES[i] for i in c.participants) + "}"
        print(f"  obs {c.index}: {seq} field {field}  log p = "
              f"{c.log_likelihood:+.6f}")

    print("\n" + "-" * 68)
    print("Error-semantics boundary: a repeated object is rejected")
    print("-" * 68)
    illegal = Ranking((0, 2, 0), (0, 1, 2, 3, 4))  # object 0 appears twice
    print(f"attempting fit with ranking {tuple(illegal.ranked)} "
          "(duplicate index 0) ...")
    try:
        fit_plackett_luce([illegal], n_objects=len(NAMES), lam=lam)
    except ValueError as exc:
        print(f"ValueError raised as designed: {exc}")
    else:  # pragma: no cover - would violate the documented contract
        raise AssertionError("duplicate object was not rejected")


if __name__ == "__main__":
    main()
