"""Fixed-input demo: fit penalized Plackett-Luce on deterministic synthetic data,
then evaluate precedence-constrained order likelihoods by exact enumeration.

Run:  python demo.py

Everything is computed live (no pre-recorded outputs, no network, no third
party). The fit data are generated by a small deterministic LCG sampler
drawing Plackett-Luce stages from fixed true abilities. The demo prints:
  1. a normal fit result (status, abilities, contributions, ranking probs);
  2. an actually triggered input rejection (duplicated object in a ranking);
  3. constrained-order likelihoods: empty constraints, a single edge, a total
     chain, the 6-candidate enumeration bound, and an actually triggered
     rejection of contradictory (cyclic) precedence constraints.
"""
import math
import time

from plackett_luce import (
    ConvergenceStatus,
    Observation,
    OrderConstraint,
    PLInputError,
    constrained_order_probability,
    fit_plackett_luce,
    ranking_probability,
)

N_OBJECTS = 5
TRUE_THETA = [0.9, 0.35, -0.1, -0.45, -0.7]
LAM = 0.05
N_ROUNDS = 400
TOP_K = 3


def make_observations(seed=20260923):
    """Deterministic top-k samples; every second round excludes one object."""
    state = seed

    def rng():
        # Numerical Recipes LCG: deterministic, standard-library only.
        nonlocal state
        state = (1664525 * state + 1013904223) & 0xFFFFFFFF
        return state / 4294967296.0

    observations = []
    for t in range(N_ROUNDS):
        # Alternating participant sets: even rounds all five objects; odd
        # rounds object 4 is absent, so it must never enter those denominators.
        participants = tuple(range(N_OBJECTS)) if t % 2 == 0 else (0, 1, 2, 3)
        remaining = list(participants)
        ranking = []
        for _ in range(min(TOP_K, len(participants))):
            weights = [math.exp(TRUE_THETA[i]) for i in remaining]
            total = math.fsum(weights)
            u = rng() * total
            cumulative = 0.0
            chosen = remaining[-1]
            for idx, w in zip(remaining, weights):
                cumulative += w
                if u <= cumulative:
                    chosen = idx
                    break
            ranking.append(chosen)
            remaining.remove(chosen)
        observations.append(Observation(tuple(ranking), participants))
    return observations


def main():
    started = time.perf_counter()

    print("=== Plackett-Luce partial-ranking fit demo ===")
    print(f"objects n={N_OBJECTS}, top-{TOP_K} samples: {N_ROUNDS}, "
          f"lambda={LAM}")
    observations = make_observations()
    print(f"(participant sets alternate: even rounds all {N_OBJECTS} "
          f"objects, odd rounds exclude object {N_OBJECTS - 1})")

    result = fit_plackett_luce(observations, N_OBJECTS, lam=LAM)
    print("\n-- normal result --")
    print("status        :", result.status.value)
    print("converged     :", result.converged)
    print("iterations    :", result.iterations)
    print("gradient norm :", f"{result.gradient_norm:.3e}")
    print("message       :", result.message)
    print("log likelihood:", f"{result.log_likelihood:.6f}")
    print("penalized f   :", f"{result.penalized_objective:.6f}")

    print("\nobject:   fitted theta   true theta   (mean-shifted true)")
    true_mean = math.fsum(TRUE_THETA) / N_OBJECTS
    true_shifted = [v - true_mean for v in TRUE_THETA]
    for i in range(N_OBJECTS):
        print(f"  {i}: {result.theta[i]:+12.4f}   {TRUE_THETA[i]:+8.3f}"
              f"   {true_shifted[i]:+12.4f}")
    print("sum(fitted theta) =", f"{math.fsum(result.theta):+.2e}")

    print("\nper-observation log contributions (first 5):")
    for i, c in enumerate(result.log_contributions[:5]):
        print(f"  obs {i}: ranking={observations[i].ranking} "
              f"participants={observations[i].participants} logP={c:.6f}")
    print("sum(contributions) =", f"{math.fsum(result.log_contributions):.6f}",
          "== log_likelihood")

    # Ranking probabilities under the fitted abilities.
    theta = list(result.theta)
    p_full = ranking_probability((0, 1, 2), theta)
    p_top1 = ranking_probability((0,), theta)
    p_subset = ranking_probability((0, 1), theta, participants=(0, 1, 4))
    print("\nranking probabilities under fitted abilities:")
    print(f"  P(order 0>1>2 among all {N_OBJECTS}) = {p_full:.6f}")
    print(f"  P(object 0 is top-1 among all {N_OBJECTS}) = {p_top1:.6f}")
    print(f"  P(0>1 among participants {{0,1,4}}) = {p_subset:.6f}")
    print("  (unranked object 4 stays in every remaining denominator)")

    # Actual rejection boundary: duplicated object inside one ranking.
    print("\n-- rejection boundary: duplicated object in a ranking --")
    bad = [Observation((0, 1, 0)), Observation((2,))]
    try:
        fit_plackett_luce(bad, N_OBJECTS, lam=LAM)
    except PLInputError as exc:
        print("PLInputError raised as required:")
        print(" ", exc)

    # ------------------------------------------------------------------ #
    # Precedence-constrained order likelihood (exact linear-extension sum)
    # ------------------------------------------------------------------ #
    print("\n" + "=" * 60)
    print("constrained-order likelihoods under the fitted abilities")
    print("=" * 60)
    print("(each likelihood sums full-order PL probabilities over every")
    print(" legal linear extension; unordered pairs are alternatives, not ties)")

    # 1. Empty constraints on 4 candidates: 4! = 24 extensions, total 1.
    cands4 = (0, 1, 2, 3)
    r_empty = constrained_order_probability(None, cands4, theta)
    print("\n-- normal: no constraints over candidates 0..3 --")
    print(f"  legal linear extensions: {r_empty.n_extensions} (= 4!)")
    print(f"  summed likelihood      : {r_empty.likelihood:.6f} "
          "(must be 1: all orders partition the space)")

    # 2. A single precedence edge: strong 0 must finish ahead of weak 3.
    r_edge = constrained_order_probability(
        [OrderConstraint(0, 3)], cands4, theta, return_extensions=True)
    print("\n-- normal: one constraint '0 before 3' over 0..3 --")
    print(f"  legal linear extensions: {r_edge.n_extensions} "
          "(half of 24 = 12)")
    print(f"  summed likelihood      : {r_edge.likelihood:.6f}")
    print("  first 3 legal extensions:",
          ", ".join("".join(map(str, e)) for e in r_edge.extensions[:3]))

    # 3. A total chain fixes one full order.
    chain = [OrderConstraint(0, 1), OrderConstraint(1, 2),
             OrderConstraint(2, 3)]
    r_chain = constrained_order_probability(chain, cands4, theta)
    p_direct = ranking_probability((0, 1, 2, 3), theta, participants=cands4)
    print("\n-- boundary: total chain 0>1>2>3 fixes the entire order --")
    print(f"  legal extensions: {r_chain.n_extensions}")
    print(f"  summed likelihood: {r_chain.likelihood:.6f}")
    print(f"  direct P(0>1>2>3): {p_direct:.6f} (the two must be equal)")

    # 4. Worst-case enumeration at the interface bound: 6 candidates, no
    #    constraints -> 6! = 720 full orders.
    theta6 = [0.3, -0.1, 0.25, -0.55, 0.4, -0.3]
    r6 = constrained_order_probability(None, tuple(range(6)), theta6)
    print("\n-- boundary: 6 candidates, no constraints, 6! = 720 extensions --")
    print(f"  legal extensions: {r6.n_extensions}")
    print(f"  summed likelihood: {r6.likelihood:.6f}")

    # 5. Single candidate: trivial event with one extension and probability 1.
    r1 = constrained_order_probability(None, (2,), theta)
    print("\n-- boundary: one candidate --")
    print(f"  legal extensions: {r1.n_extensions}")
    print(f"  summed likelihood: {r1.likelihood:.6f}")

    # 6. Actual failure: contradictory requirements close a directed cycle.
    print("\n-- failure: contradictory constraints 0>1, 1>2, 2>0 --")
    try:
        constrained_order_probability(
            [OrderConstraint(0, 1), OrderConstraint(1, 2),
             OrderConstraint(2, 0)], (0, 1, 2), theta)
    except PLInputError as exc:
        print("PLInputError raised as required:")
        print(" ", exc)

    elapsed = time.perf_counter() - started
    print(f"\nelapsed: {elapsed:.2f} s")
    if result.status != ConvergenceStatus.CONVERGED:
        raise SystemExit("demo fit did not converge")
    if not (r_empty.likelihood == 1.0 and r_chain.n_extensions == 1
            and r6.n_extensions == 720):
        raise SystemExit("demo constrained-order checks failed")


if __name__ == "__main__":
    main()
